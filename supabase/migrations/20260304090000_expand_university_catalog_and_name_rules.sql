-- Make trigger helper resilient even if a table doesn't have updated_at.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new := jsonb_populate_record(new, to_jsonb(new) || jsonb_build_object('updated_at', now()));
  return new;
end;
$$;

