alter table public.profiles
  add constraint profiles_display_name_allowed_check
  check (public.display_name_allowed(display_name));

alter table public.profiles
  drop constraint if exists profiles_real_name_allowed_check;

alter table public.profiles
  add constraint profiles_real_name_allowed_check
