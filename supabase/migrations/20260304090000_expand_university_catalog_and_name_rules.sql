create or replace function public.normalize_name_for_moderation(value text)
returns text
language sql
immutable
as $$
  select trim(
    regexp_replace(
      translate(lower(coalesce(value, '')), '@$!0134578+|9', 'asioieastbtig'),
      '[^a-z0-9]+',
      ' ',
      'g'
    )
  );
$$;

create or replace function public.name_contains_blocked_term(value text)
returns boolean
language sql
immutable
as $$
  with normalized as (
    select public.normalize_name_for_moderation(value) as normalized_value
  ),
  tokens as (
    select unnest(
      regexp_split_to_array(
        (select normalized_value from normalized),
        '\s+'
      )
    ) as token
  ),
  blocked_words as (
    select unnest(
      array[
        'fuck', 'fucker', 'fucking', 'motherfucker', 'motherfucking',
        'shit', 'shitty', 'bullshit', 'dipshit', 'asshole', 'jackass', 'dumbass',
        'badass', 'bastard', 'bitch', 'bitches', 'sonofabitch', 'cunt', 'dick',
        'dickhead', 'cock', 'cocksucker', 'prick', 'twat', 'wanker', 'slut',
        'whore', 'skank', 'pussy', 'faggot', 'retard', 'retarded', 'nigger',
        'nigga', 'chink', 'spic', 'kike', 'gook', 'wetback', 'raghead', 'tranny',
        'shemale', 'rapist', 'pedophile', 'incest', 'bestiality', 'blowjob',
        'handjob', 'cumshot', 'porn', 'pornhub', 'xvideos', 'xnxx', 'onlyfans',
        'hentai', 'suicide', 'nazis', 'terrorist'
      ]::text[]
    ) as term
  ),
  blocked_phrases as (
    select unnest(
      array[
        'kill all', 'die bitch', 'self harm', 'heil hitler', 'son of a bitch',
        'go kill yourself'
      ]::text[]
    ) as phrase
  )
  select exists (
    select 1 from tokens t
    join blocked_words b on b.term = t.token
  ) or exists (
    select 1
    from normalized n
    join blocked_phrases p
      on (' ' || n.normalized_value || ' ') like ('% ' || p.phrase || ' %')
  );
$$;

create or replace function public.display_name_allowed(name_input text)
returns boolean
language sql
immutable
as $$
  select
    name_input is not null
    and char_length(trim(name_input)) between 2 and 16
    and trim(name_input) ~ '^[A-Za-z0-9 ._''-]+$'
    and not public.name_contains_blocked_term(trim(name_input));
$$;

create or replace function public.real_name_allowed(name_input text)
returns boolean
language sql
immutable
as $$
  select
    name_input is null
    or (
      char_length(trim(name_input)) between 1 and 32
      and trim(name_input) ~ '^[A-Za-z ._''-]+$'
      and not public.name_contains_blocked_term(trim(name_input))
    );
$$;

update public.profiles
set display_name = left(regexp_replace(trim(display_name), '\s+', ' ', 'g'), 16)
where display_name is not null;

update public.profiles
set display_name = 'Student'
where not public.display_name_allowed(display_name);

update public.profiles
set real_name = null
where real_name is not null
  and not public.real_name_allowed(real_name);

